"""Aggregate per-decoder summaries from outputs/{single,multi}/ into Markdown tables.

Reads every JSON file under
    outputs/single/         (single-draft sweeps)
    outputs/multi/          (multi-draft B sweeps)
and prints one Markdown table per (cell, run) showing AATPS, TR (tok/s),
ANLPPT-{U, Li, PL}, LPPL, KL_WS_ratio, and TPR_Gamma at the configured T grid.

The summary block is read from the `summary` key that
experiments/run_{single,multi}_draft.py writes at the end of each run, so
no re-aggregation is performed --- this script is just a Markdown
formatter on top of those numbers.

Usage:
    python -m experiments.make_summary_tables               # both folders
    python -m experiments.make_summary_tables --kind single # only single
    python -m experiments.make_summary_tables --kind multi  # only multi
    python -m experiments.make_summary_tables --out FILE    # also write to FILE
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

DEFAULT_ROOT = Path("outputs")
T_GRID = [8, 16, 24, 32, 48, 64, 96, 128]


def fmt(x, n=3):
    if x is None:
        return "–"
    if isinstance(x, float):
        if x != x:        # NaN
            return "–"
        return f"{x:.{n}f}"
    return str(x)


def cell_label(cfg):
    target = (cfg.get("target_model") or "").lower()
    if "qwen" in target:
        model = "Qwen2.5-7B" if "qwen2.5-7b" in target else (
                "Qwen2.5-32B-AWQ" if "32b" in target else "Qwen")
    elif "vicuna" in target:
        model = "Vicuna-7b-v1.5"
    else:
        model = cfg.get("target_model", "?")
    ds_raw = (cfg.get("dataset") or "").lower()
    ds = {"cnn_dailymail": "CNN/DailyMail", "eli5": "ELi5"}.get(ds_raw, ds_raw or "?")
    return f"{model} × {ds}"


def render_single_table(path):
    """One Markdown block per single-draft JSON.

    Rows are decoder_L<L>_? labels (one per (decoder, lookahead) summary
    entry).  Columns: AATPS, TR, U, Li, PL, LPPL, KL_WS, TPR_Gamma@64."""
    j = json.loads(path.read_text(encoding="utf-8"))
    cfg = j.get("config", {})
    summary = j.get("summary") or {}
    if not summary:
        return f"\n### {path.name}\n\n(no `summary` block)\n"

    out = []
    out.append(f"\n### {cell_label(cfg)} — `{path.name}`")
    out.append(
        f"`samples={cfg.get('samples')} L={cfg.get('lookaheads')} "
        f"decoders={cfg.get('decoders')}`"
    )
    out.append("")
    out.append("| decoder_L | AATPS | TR | U | Li | PL | LPPL | KL/WS | TPR$_\\Gamma$@64 |")
    out.append("|---|---:|---:|---:|---:|---:|---:|---:|---:|")
    for key, s in sorted(summary.items()):
        out.append(
            f"| {key} | {fmt(s.get('AATPS'))} | {fmt(s.get('token_rate'), 2)} "
            f"| {fmt(s.get('ANLPPT_U'))} | {fmt(s.get('ANLPPT_Li'))} "
            f"| {fmt(s.get('ANLPPT_PL'))} | {fmt(s.get('LPPL'))} "
            f"| {fmt(s.get('kl_ws_ratio'))} | {fmt(s.get('det_aaronson_at_64'))} |"
        )
    return "\n".join(out) + "\n"


def render_multi_table(path):
    """One Markdown block per multi-draft JSON.

    Same metric set as single-draft; rows are decoder_L<L>_B<B> labels."""
    j = json.loads(path.read_text(encoding="utf-8"))
    cfg = j.get("config", {})
    summary = j.get("summary") or {}
    if not summary:
        return f"\n### {path.name}\n\n(no `summary` block)\n"

    out = []
    out.append(f"\n### {cell_label(cfg)} — `{path.name}`")
    out.append(
        f"`samples={cfg.get('samples')} L={cfg.get('lookaheads')} "
        f"B={cfg.get('num_drafts')} decoders={cfg.get('decoders')}`"
    )
    out.append("")
    out.append("| decoder_L_B | AATPS | TR | U | Li | PL | LPPL | KL/WS | TPR$_\\Gamma$@64 |")
    out.append("|---|---:|---:|---:|---:|---:|---:|---:|---:|")
    for key, s in sorted(summary.items()):
        out.append(
            f"| {key} | {fmt(s.get('AATPS'))} | {fmt(s.get('token_rate'), 2)} "
            f"| {fmt(s.get('ANLPPT_U'))} | {fmt(s.get('ANLPPT_Li'))} "
            f"| {fmt(s.get('ANLPPT_PL'))} | {fmt(s.get('LPPL'))} "
            f"| {fmt(s.get('kl_ws_ratio'))} | {fmt(s.get('det_aaronson_at_64'))} |"
        )
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--kind", choices=["both", "single", "multi"], default="both")
    ap.add_argument("--root", type=Path, default=DEFAULT_ROOT,
                    help="Output root containing single/ and multi/ subfolders. "
                         "Default: outputs/. Use outputs/smoke for smoke runs.")
    ap.add_argument("--out", type=Path, default=None,
                    help="Optional output Markdown file; default prints to stdout.")
    args = ap.parse_args()

    chunks = ["# Summary tables", ""]
    chunks.append(f"_generated by `experiments/make_summary_tables.py` "
                  f"(root=`{args.root}`)_")

    if args.kind in ("both", "single"):
        single_dir = args.root / "single"
        chunks.append(f"\n## Single-draft runs (`{single_dir.as_posix()}/`)")
        files = sorted(p for p in single_dir.glob("*.json"))
        if not files:
            chunks.append("\n_(no JSON files found)_")
        for p in files:
            chunks.append(render_single_table(p))

    if args.kind in ("both", "multi"):
        multi_dir = args.root / "multi"
        chunks.append(f"\n## Multi-draft runs (`{multi_dir.as_posix()}/`)")
        files = sorted(p for p in multi_dir.glob("*.json"))
        if not files:
            chunks.append("\n_(no JSON files found)_")
        for p in files:
            chunks.append(render_multi_table(p))

    text = "\n".join(chunks)
    if args.out:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(text, encoding="utf-8")
        print(f"wrote {args.out}")
    else:
        print(text)


if __name__ == "__main__":
    main()
